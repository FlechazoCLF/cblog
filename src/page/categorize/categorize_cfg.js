/****************************************************************************************************
* categorize_cfg_item_get()
****************************************************************************************************/
export function categorize_cfg_item_get(category) {
    let item = null;

    do
    {
        /* check parameter */
        if(category == "")
        {
            continue
        }
        /* impletement */
        item  = article_cfg_category_get(category);
    }while(0);

    return item ;
}

/****************************************************************************************************
* categorize_cfg_item_add()
****************************************************************************************************/
export function categorize_cfg_item_add(category,description,icon,color) {
    let item = null;

    do
    {
        /* check parameter */
        if((category == "") || (description == "") || (icon == "") || (color == ""))
        {
            continue
        }
        /* impletement */
        item  = article_cfg_category_add(category,description,icon,color);
    }while(0);

    return item ;
}

