/****************************************************************************************************
* Wonderful_chat_cfg_list_user_get()
****************************************************************************************************/
export function Wonderful_chat_cfg_list_user_get(user) {
    let result = null;
    do
    {
        /* check parameter */
        if(user === undefined || user === null || user === "")
        {
            continue;
        }
        /* find */
        for (let i = 0; i < chat_cfg_list.length; i++)
        {
            if (chat_cfg_list[i].user === user)
            {
                result = chat_cfg_list[i];
                break;
            }
        }
    }while(0);

    return result;
}

