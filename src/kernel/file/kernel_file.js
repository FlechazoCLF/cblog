/****************************************************************************************************
* kernel_file_read()
****************************************************************************************************/
export async function kernel_file_read(article) {
    let content = null;

    do
    {
        /* check */
        if(article == null)
        {
            continue;
        }
        /* path article path / readme.md */
        const url = `/${encodeURIComponent(article)}/readme.md`;
        /* read */
        try{
            /* fetch */
            const response = await fetch(url);
            if (!response.ok) 
            {
                throw new Error(`HTTP error! status: ${response.status}`);
            }
            /* content */
            content = await response.text();
        } catch (error) {
            content = "# 文章加载失败\n\n抱歉,无法加载该文章。";
        }
    }while(0);
    
    return content;
}

/****************************************************************************************************
* kernel_file_get_frontmatter()
****************************************************************************************************/
export function kernel_file_get_frontmatter(content) {
    const result = {};

    do
    {
        /* check */
        if(content == "")
        {
            continue;
        }
        /* get date from markdown */
        const match = content.match(/---\s*([\s\S]*?)\s*---/);
        if(match == null)
        {
            continue;
        }
        /* get line */
        const lines = match[1].split('\n');
        lines.forEach(line => {
            /* split : */
            const [key, ...rest] = line.split(':');
            if (key && rest.length > 0) 
            {
                /* result */
                result[key.trim()] = rest.join(':').trim();
            }
        });
    }while(0);

    return result;
}

